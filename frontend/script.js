// Display summary in output
function displaySummary(summary, stats = null) {
    const outputDiv = document.getElementById('output');
    const exportOptions = document.getElementById('exportOptions');
    
    currentSummary = summary;
    currentStats = stats;
    
    let statsHtml = '';
    if (stats) {
        statsHtml = `
            <div class="summary-stats">
                📊 ${stats.original_length.toLocaleString()} characters → ${stats.summary_length.toLocaleString()} characters (${stats.compression} compression)
            </div>
        `;
    }
    
    outputDiv.innerHTML = `
        <div style="line-height: 1.6; text-align: center; max-width: 100%; margin: 0 auto;">
            ${summary}
        </div>
        ${statsHtml}
    `;
    
    exportOptions.style.display = 'block';
}

// Clear all
function clearAll() {
    if (textInput) {
        textInput.value = '';
        const counter = document.getElementById('charCount');
        if (counter) counter.textContent = '0 characters';
    }
    
    selectedFile = null;
    const fileInputElement = document.getElementById('fileInput');
    if (fileInputElement) fileInputElement.value = '';
    const fileInfo = document.getElementById('fileInfo');
    if (fileInfo) fileInfo.style.display = 'none';
    
    const outputDiv = document.getElementById('output');
    if (outputDiv) {
        outputDiv.innerHTML = '<p class="placeholder">Your summary will appear here</p>';
    }
    
    const exportOptions = document.getElementById('exportOptions');
    if (exportOptions) exportOptions.style.display = 'none';
    
    const errorDiv = document.getElementById('error');
    if (errorDiv) errorDiv.style.display = 'none';
    
    currentSummary = null;
    currentStats = null;
    
    showNotification('🧹 All cleared!');
}

// Show error
function showError(message) {
    const errorDiv = document.getElementById('error');
    errorDiv.textContent = `⚠️ ${message}`;
    errorDiv.style.display = 'block';
    setTimeout(() => {
        errorDiv.style.display = 'none';
    }, 5000);
}

// Main summarize function
async function summarize() {
    const isFileTab = document.getElementById('fileTab').classList.contains('active');
    const loadingDiv = document.getElementById('loading');
    const summarizeBtn = document.getElementById('summarizeBtn');
    const outputDiv = document.getElementById('output');
    const exportOptions = document.getElementById('exportOptions');
    
    try {
        loadingDiv.style.display = 'block';
        summarizeBtn.disabled = true;
        outputDiv.innerHTML = '<p class="placeholder">🤔 AI is analyzing your document...</p>';
        exportOptions.style.display = 'none';
        document.getElementById('error').style.display = 'none';
        
        let response;
        
        if (isFileTab && selectedFile) {
            const formData = new FormData();
            formData.append('file', selectedFile);
            response = await fetch(`${API_URL}/summarize`, {
                method: 'POST',
                body: formData
            });
        } else {
            const text = textInput ? textInput.value.trim() : '';
            if (!text) throw new Error('Please enter some text to summarize');
            if (text.length < 30) throw new Error(`Text too short (${text.length} chars). Minimum 30 characters required.`);
            
            response = await fetch(`${API_URL}/summarize`, {
                method: 'POST',
                headers: { 'Content-Type': 'application/json' },
                body: JSON.stringify({ text: text })
            });
        }
        
        const data = await response.json();
        
        if (!response.ok) throw new Error(data.error || 'Summarization failed');
        
        if (data.summary) {
            displaySummary(data.summary, data.stats);
            showNotification('✅ Summary generated successfully!');
        } else {
            throw new Error('No summary received from server');
        }
        
    } catch (error) {
        console.error('Error:', error);
        showError(error.message);
        outputDiv.innerHTML = '<p class="placeholder">❌ Error generating summary. Please try again.</p>';
        exportOptions.style.display = 'none';
    } finally {
        loadingDiv.style.display = 'none';
        summarizeBtn.disabled = false;
    }
}

// Check backend health
async function checkBackend() {
    try {
        const response = await fetch(`${API_URL}/health`);
        if (response.ok) {
            console.log('✅ Backend is healthy');
        }
    } catch (error) {
        console.error('❌ Cannot connect to backend');
        showError('Cannot connect to backend server. Please make sure Flask server is running on port 5000');
    }
}

