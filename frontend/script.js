// API Configuration
const API_URL = 'http://127.0.0.1:5000';

let selectedFile = null;
let currentSummary = null;
let currentStats = null;

// Tab switching
function switchTab(tab) {
    const textTab = document.getElementById('textTab');
    const fileTab = document.getElementById('fileTab');
    const btns = document.querySelectorAll('.tab-btn');
    
    if (tab === 'text') {
        textTab.classList.add('active');
        fileTab.classList.remove('active');
        btns[0].classList.add('active');
        btns[1].classList.remove('active');
    } else {
        textTab.classList.remove('active');
        fileTab.classList.add('active');
        btns[0].classList.remove('active');
        btns[1].classList.add('active');
    }
}

// File upload handling
const fileInput = document.getElementById('fileInput');
if (fileInput) {
    fileInput.addEventListener('change', function(e) {
        if (e.target.files.length > 0) {
            selectedFile = e.target.files[0];
            const fileInfo = document.getElementById('fileInfo');
            fileInfo.innerHTML = `✅ Selected: ${selectedFile.name} (${(selectedFile.size / 1024).toFixed(2)} KB)`;
            fileInfo.style.display = 'block';
        }
    });
}

// Character counter
const textInput = document.getElementById('textInput');
if (textInput) {
    textInput.addEventListener('input', function() {
        const len = this.value.length;
        const counter = document.getElementById('charCount');
        counter.textContent = `${len} characters`;
        
        if (len > 0 && len < 30) {
            counter.style.color = '#f44336';
        } else {
            counter.style.color = '#999';
        }
    });
}

// Show notification
function showNotification(message, isError = false) {
    const notification = document.createElement('div');
    notification.textContent = message;
    notification.className = 'notification';
    if (isError) {
        notification.style.background = '#dc3545';
    } else {
        notification.style.background = '#28a745';
    }
    document.body.appendChild(notification);
    
    setTimeout(() => {
        notification.remove();
    }, 3000);
}

// Copy summary to clipboard
function copySummary() {
    if (!currentSummary) {
        showNotification('No summary to copy! Generate a summary first.', true);
        return;
    }
    
    const tempDiv = document.createElement('div');
    tempDiv.innerHTML = currentSummary;
    const plainText = tempDiv.textContent || tempDiv.innerText || currentSummary;
    
    navigator.clipboard.writeText(plainText).then(() => {
        showNotification('✅ Summary copied to clipboard!');
    }).catch(() => {
        showNotification('❌ Failed to copy summary', true);
    });
}

// Download as TXT
function downloadAsTXT() {
    if (!currentSummary) {
        showNotification('No summary to download! Generate a summary first.', true);
        return;
    }
    
    const tempDiv = document.createElement('div');
    tempDiv.innerHTML = currentSummary;
    let summaryText = tempDiv.textContent || tempDiv.innerText || currentSummary;
    
    const date = new Date();
    const timestamp = date.toISOString().slice(0, 19).replace(/:/g, '-');
    
    let fileContent = `========================================\n`;
    fileContent += `AI DOCUMENT SUMMARIZER - SUMMARY\n`;
    fileContent += `========================================\n`;
    fileContent += `Generated: ${date.toLocaleString()}\n`;
    if (currentStats) {
        fileContent += `Original Length: ${currentStats.original_length} characters\n`;
        fileContent += `Summary Length: ${currentStats.summary_length} characters\n`;
        fileContent += `Compression: ${currentStats.compression}\n`;
    }
    fileContent += `========================================\n\n`;
    fileContent += `SUMMARY:\n`;
    fileContent += `========================================\n\n`;
    fileContent += summaryText;
    fileContent += `\n\n========================================\n`;
    fileContent += `Generated by AI Document Summarizer\n`;
    fileContent += `========================================\n`;
    
    const blob = new Blob([fileContent], { type: 'text/plain;charset=utf-8' });
    const link = document.createElement('a');
    const url = URL.createObjectURL(blob);
    link.href = url;
    link.download = `summary_${timestamp}.txt`;
    document.body.appendChild(link);
    link.click();
    document.body.removeChild(link);
    URL.revokeObjectURL(url);
    
    showNotification('✅ TXT file downloaded!');
}

